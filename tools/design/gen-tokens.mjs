// docs/design/tokens.json (the design system's tokens, same file the design-system page reads) ->
// client/lib/ui/yz_tokens.dart (a ThemeExtension with every colour per theme, and the lengths as constants).
//
//   node tools/design/gen-tokens.mjs
//
// Change a value in tokens.json, run this, hot reload. Never edit yz_tokens.dart by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const tokens = JSON.parse(readFileSync(join(repo, 'docs/design/tokens.json'), 'utf8'));
const out = join(repo, 'client/lib/ui/yz_tokens.dart');

const camel = (s) => s.replace(/[-.](\w)/g, (_, c) => c.toUpperCase());
const themes = tokens.color.themes.map((t) => t.id);
const first = themes[0];

/** '#rrggbb' or '#rrggbbaa' -> 0xAARRGGBB */
function argb(hex) {
  const h = hex.replace('#', '').toLowerCase();
  const full = h.length === 3 || h.length === 4 ? [...h].map((c) => c + c).join('') : h;
  const rgb = full.slice(0, 6), a = full.length === 8 ? full.slice(6, 8) : 'ff';
  return `0x${(a + rgb).toUpperCase()}`;
}
const valueFor = (t, theme) => (typeof t.value === 'string' ? t.value : t.value[theme] ?? t.value[first]);
const colors = tokens.color.tokens;
const dartDoc = (s) => (s ? `  /// ${s.replace(/\n/g, ' ')}\n` : '');

const fields = colors.map((t) => `${dartDoc(t.usage)}  final Color ${camel(t.name)};`).join('\n');
const ctorParams = colors.map((t) => `required this.${camel(t.name)}`).join(', ');
const instances = themes
  .map((theme) => {
    const args = colors.map((t) => `    ${camel(t.name)}: Color(${argb(valueFor(t, theme))}),`).join('\n');
    return `  static const ${theme} = YzTokens(\n${args}\n  );`;
  })
  .join('\n\n');
const copyWithParams = colors.map((t) => `Color? ${camel(t.name)}`).join(', ');
const copyWithArgs = colors.map((t) => `${camel(t.name)}: ${camel(t.name)} ?? this.${camel(t.name)}`).join(', ');
const lerpArgs = colors.map((t) => `${camel(t.name)}: Color.lerp(${camel(t.name)}, other.${camel(t.name)}, t)!`).join(', ');

const px = (v) => String(parseFloat(v));
const lengths = (family, prefix = '', skip = []) =>
  (tokens[family]?.tokens ?? [])
    .filter((t) => !skip.includes(t.name) && /^-?[\d.]+(px)?$/.test(String(t.value)))
    .map((t) => `${dartDoc(t.usage)}  static const double ${prefix}${camel(t.name)} = ${px(t.value)};`)
    .join('\n');
const styles = tokens.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: s.family ?? g.family })));
const styleConsts = styles
  .map((s) => {
    const parts = [`fontSize: ${px(s.fontSize)}`, `height: ${(parseFloat(s.lineHeight) / parseFloat(s.fontSize)).toFixed(3)}`, `fontWeight: FontWeight.w${s.fontWeight}`];
    if (s.letterSpacing) parts.push(`letterSpacing: ${px(s.letterSpacing)}`);
    if (s.family === 'latin') parts.push('fontFeatures: [FontFeature.tabularFigures()]');
    return `${dartDoc(s.usage)}  static const ${camel(s.name)} = TextStyle(${parts.join(', ')});\n  static const ${camel(s.name)}Family = YzFamily.${s.family};`;
  })
  .join('\n');

const dart = `// GENERATED by tools/design/gen-tokens.mjs from docs/design/tokens.json. Do not edit by hand.
// ignore_for_file: constant_identifier_names
import 'package:material_ui/material_ui.dart';

/// The design system's colours for one theme (${themes.join(', ')}), as a [ThemeExtension]: \`YzTokens.of(context)\`.
@immutable
class YzTokens extends ThemeExtension<YzTokens> {
  const YzTokens({${ctorParams}});

${fields}

${instances}

  static YzTokens of(BuildContext context) => Theme.of(context).extension<YzTokens>() ?? (Theme.of(context).brightness == Brightness.light ? ${themes.includes('light') ? 'light' : first} : ${first});

  @override
  YzTokens copyWith({${copyWithParams}}) => YzTokens(${copyWithArgs});

  @override
  YzTokens lerp(YzTokens? other, double t) => other == null ? this : YzTokens(${lerpArgs});
}

/// Spacing, radii and sizes, in logical pixels.
abstract final class Yz {
${lengths('spacing')}
${lengths('radius')}
${lengths('size', '', ['poster-ratio'])}
  /// Poster width / height.
  static const double posterRatio = ${tokens.size?.tokens?.find((t) => t.name === 'poster-ratio')?.value ?? 0.7};
}

/// Which family a text style is set in.
enum YzFamily { ${Object.keys(tokens.type.families).join(', ')} }

/// The type scale (sizes, line heights, weights; the family is the matching \`YzFamily\`).
abstract final class YzType {
${styleConsts}

  /// Font stacks per family, for \`fontFamily\` + \`fontFamilyFallback\`.
  static const families = <YzFamily, List<String>>{
${Object.entries(tokens.type.families)
  .map(([k, v]) => `    YzFamily.${k}: [${v.split(',').map((s) => s.trim().replace(/^"|"$/g, '')).filter((s) => !/^(system-ui|sans-serif|serif|monospace)$/.test(s)).map((s) => `'${s}'`).join(', ')}],`)
  .join('\n')}
  };
}
`;
writeFileSync(out, dart);
console.log(`wrote ${out}: ${colors.length} colours × ${themes.length} themes, ${styles.length} text styles`);
